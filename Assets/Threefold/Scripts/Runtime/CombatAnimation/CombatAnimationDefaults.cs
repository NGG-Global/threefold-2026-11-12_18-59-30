using System.Collections.Generic;
using Threefold.Magic;

namespace Threefold.CombatAnimation
{
    /// <summary>
    /// The Mage's starting combat animation slots. The setup command writes them into the Mage's
    /// animation set asset once; after that the asset is the truth and can be tuned freely.
    ///
    /// Every clip comes from Quaternius' Universal Animation Library 1 or 2 (CC0), built into the Mage's
    /// model by Tools/blender/build_mage.py. The moments in each clip were measured by
    /// Tools/blender/analyse_combat_clips.py (30 frames per second):
    /// - contact of a punch or palm: the frame of the striking hand's furthest reach after its fastest frame;
    /// - contact of a swing: the striking hand's fastest frame;
    /// - hit window: from the fastest frame (or two frames before contact for a swing) to two frames after
    ///   contact; the effect cue leads the hit window by two frames;
    /// - recovery end: the frame from which the striking hand stays within 5 cm of where the clip leaves it,
    ///   or earlier where the clip goes on into a second movement that is not wanted.
    /// None of these clips was made for the Mage. They are placeholders chosen for silhouette and timing,
    /// listed with the reasons in Docs/CombatAnimationArchitecture.md. Nothing here has been seen in Unity.
    ///
    /// Since version 2 the stances and strikes are the martial styles of Docs/MartialStyles.md: clips derived from
    /// library motion by Tools/blender/martial_styles.py, measured by Tools/blender/analyse_martial_styles.py on the
    /// exported model. Each strike starts from its discipline's stance and returns to it, so a strike follows the
    /// stance or the strike before it without a jump.
    /// </summary>
    public static class CombatAnimationDefaults
    {
        /// <summary>
        /// The version of the slots a newly generated set holds. 1: the first placeholders (Sprint 1). 2: the martial
        /// styles: new stances and strikes, three Aegis strikes.
        /// </summary>
        public const int DataVersion = 2;

        /// <summary>Every clip the defaults use. The Mage model must contain all of them.</summary>
        public static readonly string[] RequiredClips =
        {
            "Arcane_Stance_Loop", "Arcane_RisingPalm", "Arcane_CirclingPalm", "Arcane_Lance",
            "Flame_Stance_Loop", "Flame_Punch", "Flame_Hook", "Flame_Flare",
            "Aegis_Stance_Loop", "Aegis_ForcePalm", "Aegis_Forearm", "Aegis_Slam",
            "Spell_Simple_Enter", "Spell_Simple_Idle_Loop", "SpellShoot", "Spell_Simple_Exit", "OverhandThrow",
            "Shield_OneShot", "Push_Loop",
            "Idle_Shield_Loop", "Idle_Shield_Break", "Hit_Chest", "Hit_Head", "NinjaJump_Start", "Death01",
        };

        /// <summary>
        /// The stance and attack clips of version 1, per discipline (stance first; "|m" marks a mirrored slot). A set
        /// whose stance and attacks still match these was never changed by hand, so the upgrade replaces them.
        /// </summary>
        private static readonly string[][] Version1Clips =
        {
            new[] { "Punch_Jab", "Punch_Jab", "Punch_Cross", "Spell_Simple_Enter" },
            new[] { "Sword_Idle", "Sword_Attack", "Sword_Attack|m", "Sword_Regular_B" },
            new[] { "Sword_Block", "Shield_OneShot", "Melee_Hook" },
        };

        /// <summary>
        /// Brings a library generated by an earlier version up to date, once. A discipline whose stance and attack
        /// slots are still that version's defaults gets the current ones; a discipline changed by hand is kept as it
        /// is and named in <paramref name="kept"/>. Charge, block, reaction, aerial and defeat slots and the tuning
        /// are never changed. Returns the number of disciplines updated.
        /// </summary>
        public static int Upgrade(CombatAnimationLibrary library, int fromVersion, List<MagicDiscipline> kept = null)
        {
            if (library?.disciplines == null || fromVersion >= DataVersion)
            {
                return 0;
            }

            int updated = 0;
            CombatAnimationLibrary current = CreateMage();
            foreach (DisciplineAnimationSet set in library.disciplines)
            {
                if (set == null)
                {
                    continue;
                }

                if (!MatchesVersion1(set))
                {
                    kept?.Add(set.discipline);
                    continue;
                }

                DisciplineAnimationSet latest = current.GetDiscipline(set.discipline);
                if (latest == null)
                {
                    continue;
                }

                set.stance = latest.stance;
                set.attacks = latest.attacks;
                updated++;
            }

            return updated;
        }

        private static bool MatchesVersion1(DisciplineAnimationSet set)
        {
            int index = (int)set.discipline;
            if (index < 0 || index >= Version1Clips.Length || set.attacks == null)
            {
                return false;
            }

            string[] clips = Version1Clips[index];
            if (set.attacks.Length != clips.Length - 1 || !Same(set.stance, clips[0]))
            {
                return false;
            }

            for (int i = 0; i < set.attacks.Length; i++)
            {
                if (!Same(set.attacks[i], clips[i + 1]))
                {
                    return false;
                }
            }

            return true;
        }

        private static bool Same(CombatAnimationSlot slot, string clip)
        {
            bool mirrored = clip.EndsWith("|m", System.StringComparison.Ordinal);
            string name = mirrored ? clip.Substring(0, clip.Length - 2) : clip;
            return slot != null && slot.clip == name && slot.mirror == mirrored;
        }

        public static CombatAnimationLibrary CreateMage()
        {
            return new CombatAnimationLibrary
            {
                disciplines = new[] { Arcane(), Flame(), Aegis() },
                shared = Shared(),
                tuning = new CombatAnimationTuning(),
            };
        }

        // ------------------------------------------------------------ Arcane

        /// <summary>
        /// Flowing precision (Tai Chi, Baguazhang): a relaxed, alert stance with both hands open and floating; a palm
        /// that sinks and rises in an arc; the other palm circling outwards and round (the same arc, bent into a
        /// horizontal circle and played mirrored); a reaching spear hand. Every strike flows out of the stance and back
        /// into it. All upper body: Arcane strikes at full movement speed. The charge raises and holds the casting hand;
        /// the release is the existing casting gesture.
        /// </summary>
        private static DisciplineAnimationSet Arcane()
        {
            return new DisciplineAnimationSet
            {
                discipline = MagicDiscipline.Arcane,
                stance = WithBlend(Loop("Arcane_Stance_Loop", 2.5f, CombatEffector.LeftHand), 0.25f, 0.25f),
                attacks = new[]
                {
                    // Rising Palm. 31 frames; fastest frame 9, full reach frame 13, back in the stance from frame 29.
                    Strike("Arcane_RisingPalm", 1f, CombatEffector.LeftHand, open: 0.267f, contact: 0.4f, close: 0.467f,
                        recoveryEnd: 0.933f, blendIn: 0.08f, blendOut: 0.12f),
                    // Circling Palm, mirrored: the right hand. 31 frames; fastest frame 11, reach frame 14, settled frame 29.
                    Mirrored(Strike("Arcane_CirclingPalm", 1f, CombatEffector.RightHand, open: 0.333f, contact: 0.433f,
                        close: 0.5f, recoveryEnd: 0.933f, blendIn: 0.08f, blendOut: 0.12f)),
                    // Arcane Lance. 36 frames; the spear hand reaches full extension at frame 10; settled frame 34.
                    Strike("Arcane_Lance", 1.167f, CombatEffector.LeftHand, open: 0.171f, contact: 0.257f, close: 0.314f,
                        recoveryEnd: 0.943f, blendIn: 0.08f, blendOut: 0.15f),
                },
                chargeStart = Motion("Spell_Simple_Enter", 0.533f, CombatEffector.LeftHand, effect: 0.5f),
                chargeHold = Loop("Spell_Simple_Idle_Loop", 2.1f, CombatEffector.LeftHand),
                // The casting gesture: the hand is already extended, so contact is its second frame.
                chargeRelease = Release("SpellShoot", 0.5f, CombatEffector.LeftHand, contact: 0.067f, recoveryEnd: 0.533f),
                chargeCancel = Motion("Spell_Simple_Exit", 0.433f, CombatEffector.LeftHand, effect: 0f, recoveryEnd: 0.923f),
            };
        }

        // ------------------------------------------------------------- Flame

        /// <summary>
        /// Explosive aggression (Northern Shaolin): a wide, low guard with the fists up; a straight rear-hand punch
        /// driven by the hips; a lunging hook that turns the whole body; a coiling, spinning rising sweep. The hook
        /// and the sweep use the whole body when standing. The charge mirrors the Arcane gesture into the right hand;
        /// the release is a low overhand throw along the ground, like the Flame Wave.
        /// </summary>
        private static DisciplineAnimationSet Flame()
        {
            return new DisciplineAnimationSet
            {
                discipline = MagicDiscipline.Flame,
                stance = WithBlend(Loop("Flame_Stance_Loop", 1.667f, CombatEffector.RightHand), 0.2f, 0.25f),
                attacks = new[]
                {
                    // Ember Fist. 31 frames; fastest frame 7, full extension frame 9, back in the guard from frame 27.
                    Strike("Flame_Punch", 1f, CombatEffector.RightHand, open: 0.2f, contact: 0.267f, close: 0.333f,
                        recoveryEnd: 0.867f),
                    // Ember Hook. 34 frames; fastest frame 9 (41 m/s), a lunge of 0.46 m that comes back; settled frame 32.
                    FullBody(Strike("Flame_Hook", 1.1f, CombatEffector.RightHand, open: 0.182f, contact: 0.242f, close: 0.303f,
                        recoveryEnd: 0.939f, blendOut: 0.18f)),
                    // Flare. 43 frames; coils down, then sweeps up and round, turning the hips 146 degrees; contact at
                    // the fastest frame 9; turned back to the front by frame 41.
                    FullBody(Strike("Flame_Flare", 1.4f, CombatEffector.RightHand, open: 0.143f, contact: 0.19f, close: 0.238f,
                        recoveryEnd: 0.952f, blendOut: 0.2f)),
                },
                chargeStart = Mirrored(Motion("Spell_Simple_Enter", 0.533f, CombatEffector.RightHand, effect: 0.5f)),
                chargeHold = Mirrored(Loop("Spell_Simple_Idle_Loop", 2.1f, CombatEffector.RightHand)),
                // 41 frames; the throw's fastest frame 13, settled frame 38. Full body when standing still.
                chargeRelease = FullBody(Release("OverhandThrow", 1.333f, CombatEffector.RightHand, contact: 0.3f,
                    recoveryEnd: 0.925f)),
                chargeCancel = Mirrored(Motion("Spell_Simple_Exit", 0.433f, CombatEffector.RightHand, effect: 0f,
                    recoveryEnd: 0.923f)),
            };
        }

        // ------------------------------------------------------------- Aegis

        /// <summary>
        /// Grounded power (Hung Gar): the widest and lowest stance, rooted, forearm across the chest; a palm thrust that
        /// sinks the whole body into it; a forearm strike driven by the hips; a two-handed slam that rises and crashes
        /// down into a deep lunge. The palm and the slam use the whole body when standing. Heavy anticipation, a held
        /// impact pose, then a slow rise back into the stance. The charge raises the forearm and holds it; the release
        /// is a two-handed shove.
        /// </summary>
        private static DisciplineAnimationSet Aegis()
        {
            return new DisciplineAnimationSet
            {
                discipline = MagicDiscipline.Aegis,
                stance = WithBlend(Loop("Aegis_Stance_Loop", 2.5f, CombatEffector.BothHands), 0.25f, 0.3f),
                attacks = new[]
                {
                    // Force Palm. 35 frames; the body drops as the palm drives out: fastest frame 4, contact frame 6;
                    // holds low, then rises; back in the stance from frame 30.
                    FullBody(Strike("Aegis_ForcePalm", 1.133f, CombatEffector.RightHand, open: 0.088f, contact: 0.147f,
                        close: 0.206f, recoveryEnd: 0.853f, blendIn: 0.1f, blendOut: 0.2f)),
                    // Bulwark Forearm. 29 frames; the forearm is drawn in, then driven out with the hips: contact frame 7;
                    // settled frame 27.
                    Strike("Aegis_Forearm", 0.933f, CombatEffector.LeftHand, open: 0.143f, contact: 0.214f, close: 0.286f,
                        recoveryEnd: 0.929f, blendIn: 0.1f, blendOut: 0.2f),
                    // Bulwark Slam. 41 frames; both arms rise and open, then crash down at the fastest frame 13 into a deep
                    // lunge (0.34 m, which comes back); settled frame 38.
                    FullBody(Strike("Aegis_Slam", 1.333f, CombatEffector.BothHands, open: 0.25f, contact: 0.3f, close: 0.35f,
                        recoveryEnd: 0.925f, blendIn: 0.1f, blendOut: 0.25f)),
                },
                // The forearm rises (frames 1 to 8), then holds there.
                chargeStart = Motion("Shield_OneShot", 0.833f, CombatEffector.LeftHand, effect: 0.12f, recoveryEnd: 0.28f),
                chargeHold = Hold("Shield_OneShot", 0.833f, 0.28f, CombatEffector.LeftHand),
                // A two-handed shove: the push pose, held for about 0.4 s.
                chargeRelease = WithEntry(Release("Push_Loop", 2.667f, CombatEffector.BothHands, contact: 0.45f,
                    recoveryEnd: 0.6f), 0.45f),
                // The forearm lowers: the second half of the bash.
                chargeCancel = WithEntry(Motion("Shield_OneShot", 0.833f, CombatEffector.LeftHand, effect: 0.6f,
                    recoveryEnd: 0.96f), 0.6f),
            };
        }

        // ------------------------------------------------------------- shared

        private static SharedCombatAnimations Shared()
        {
            return new SharedCombatAnimations
            {
                // The forearm across the chest: the clearest guard silhouette in the libraries.
                blockHold = Loop("Idle_Shield_Loop", 2.5f, CombatEffector.LeftHand),
                // The guard knocked aside and raised again (fastest frame 4; back up by frame 23).
                blockImpact = Reaction("Idle_Shield_Break", 1.067f, contact: 0.094f, recoveryEnd: 0.7f),
                stagger = Reaction("Hit_Chest", 0.333f, contact: 0.3f, recoveryEnd: 0.8f),
                heavyStagger = Reaction("Hit_Head", 0.433f, contact: 0.46f, recoveryEnd: 1f),
                // A leap with one knee drawn up and the right arm thrown out: the crouch before it (frames 1
                // to 5) is skipped. Whole body, in the air only; it ends on landing.
                aerialAttack = FullBody(WithEntry(Strike("NinjaJump_Start", 0.967f, CombatEffector.RightHand, open: 0.2f,
                    contact: 0.241f, close: 0.31f, recoveryEnd: 0.759f), 0.172f)),
                aerialRelease = FullBody(WithEntry(Release("NinjaJump_Start", 0.967f, CombatEffector.RightHand, contact: 0.241f,
                    recoveryEnd: 0.759f), 0.172f)),
                // Ends lying down and stays there until revived. Travels about 0.9 m from where it starts.
                defeat = FullBody(Motion("Death01", 2.4f, CombatEffector.None, effect: 0f, recoveryEnd: 1f)),
            };
        }

        // ------------------------------------------------------------ builders

        private static CombatAnimationSlot Strike(string clip, float seconds, CombatEffector effector, float open, float contact,
            float close, float recoveryEnd, float blendOut = 0.15f, float blendIn = 0.06f)
        {
            return new CombatAnimationSlot
            {
                clip = clip, clipSeconds = seconds, effector = effector, scope = CombatBodyScope.UpperBody,
                entry = 0f, hitWindowOpen = open, contact = contact, hitWindowClose = close,
                effect = System.Math.Max(0f, open - 2f / 30f / seconds), recoveryEnd = recoveryEnd,
                blendInSeconds = blendIn, blendOutSeconds = blendOut,
            };
        }

        private static CombatAnimationSlot WithBlend(CombatAnimationSlot slot, float blendIn, float blendOut)
        {
            slot.blendInSeconds = blendIn;
            slot.blendOutSeconds = blendOut;
            return slot;
        }

        private static CombatAnimationSlot Release(string clip, float seconds, CombatEffector effector, float contact,
            float recoveryEnd)
        {
            return new CombatAnimationSlot
            {
                clip = clip, clipSeconds = seconds, effector = effector, scope = CombatBodyScope.UpperBody,
                entry = 0f, hitWindowOpen = contact, contact = contact, hitWindowClose = contact, effect = contact,
                recoveryEnd = recoveryEnd, blendInSeconds = 0.06f, blendOutSeconds = 0.2f,
            };
        }

        private static CombatAnimationSlot Motion(string clip, float seconds, CombatEffector effector, float effect,
            float recoveryEnd = 1f)
        {
            return new CombatAnimationSlot
            {
                clip = clip, clipSeconds = seconds, effector = effector, scope = CombatBodyScope.UpperBody,
                entry = 0f, contact = 0f, hitWindowOpen = 0f, hitWindowClose = 0f, effect = effect,
                recoveryEnd = recoveryEnd, blendInSeconds = 0.1f, blendOutSeconds = 0.2f,
            };
        }

        private static CombatAnimationSlot Reaction(string clip, float seconds, float contact, float recoveryEnd)
        {
            return new CombatAnimationSlot
            {
                clip = clip, clipSeconds = seconds, effector = CombatEffector.None, scope = CombatBodyScope.UpperBody,
                entry = 0f, contact = contact, hitWindowOpen = contact, hitWindowClose = contact, effect = contact,
                recoveryEnd = recoveryEnd, blendInSeconds = 0.05f, blendOutSeconds = 0.2f,
            };
        }

        private static CombatAnimationSlot Loop(string clip, float seconds, CombatEffector effector)
        {
            return new CombatAnimationSlot
            {
                clip = clip, clipSeconds = seconds, effector = effector, scope = CombatBodyScope.UpperBody,
                entry = 0f, contact = 0f, hitWindowOpen = 0f, hitWindowClose = 0f, effect = 0f, recoveryEnd = 1f,
                blendInSeconds = 0.15f, blendOutSeconds = 0.2f,
            };
        }

        private static CombatAnimationSlot Hold(string clip, float seconds, float frame, CombatEffector effector)
        {
            CombatAnimationSlot slot = Loop(clip, seconds, effector);
            slot.holdPose = true;
            slot.entry = frame;
            slot.contact = frame;
            slot.hitWindowOpen = frame;
            slot.hitWindowClose = frame;
            slot.effect = frame;
            return slot;
        }

        private static CombatAnimationSlot Mirrored(CombatAnimationSlot slot)
        {
            slot.mirror = true;
            return slot;
        }

        private static CombatAnimationSlot FullBody(CombatAnimationSlot slot)
        {
            slot.scope = CombatBodyScope.FullBody;
            return slot;
        }

        /// <summary>Starts the clip later. Moments before the new entry move to it.</summary>
        private static CombatAnimationSlot WithEntry(CombatAnimationSlot slot, float entry)
        {
            slot.entry = entry;
            if (slot.contact < entry) slot.contact = entry;
            if (slot.hitWindowOpen < entry) slot.hitWindowOpen = entry;
            if (slot.hitWindowClose < entry) slot.hitWindowClose = entry;
            if (slot.effect < entry) slot.effect = entry;
            if (slot.recoveryEnd < entry) slot.recoveryEnd = entry;
            return slot;
        }
    }

using System.Collections.Generic;
using Threefold.Magic;
using UnityEngine;

namespace Threefold.CombatAnimation
{
    /// <summary>
    /// A demonstration figure for comparing the three martial styles side by side (Docs/MartialStyles.md). It loops its
    /// discipline's whole melee combo: the real combat rules decide when each strike starts, lands and recovers
    /// (<see cref="ComboShowcaseSequence"/>), the real <see cref="CombatAnimationModel"/> decides what plays, and the same
    /// <see cref="CombatAnimatorBinding"/> as the Mage's carries it out. A post in front of the figure jolts at the
    /// moment each strike lands, so the contact frame can be checked against the hit. Every few rounds it plays in slow
    /// motion (the rules' clock and the Animator slow down together), to check blends and contact frames.
    ///
    /// It deals no damage, reads no input and touches nothing but its own figure and post. Generated by
    /// Threefold > Setup > Martial Styles Showcase, which the Discipline Range setup runs.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class CombatStyleShowcase : MonoBehaviour
    {
        private static readonly int BaseColorId = Shader.PropertyToID("_BaseColor");
        private static readonly int GroundedId = Animator.StringToHash("Grounded");

        [SerializeField] private MagicDiscipline discipline;

        [Tooltip("Optional. The discipline's asset, so the timing matches tuning. Empty: the discipline's starting values.")]
        [SerializeField] private DisciplineDefinition definition;

        [SerializeField] private CombatAnimationSet animationSet;

        [Tooltip("The figure's Animator, with the Mage's generated controller.")]
        [SerializeField] private Animator figure;

        [Tooltip("Optional. Jolts at each contact.")]
        [SerializeField] private Transform target;

        [Tooltip("Optional. Tinted in the discipline's colour.")]
        [SerializeField] private Renderer marker;

        [Header("Rhythm")]
        [Tooltip("Seconds of stance between rounds.")]
        [Min(0.5f)]
        [SerializeField] private float pauseSeconds = 1.2f;

        [Tooltip("Every this many rounds, one is played in slow motion. 0: never.")]
        [Min(0)]
        [SerializeField] private int slowMotionEvery = 3;

        [Tooltip("Speed of the slow-motion round, relative to normal.")]
        [Range(0.1f, 1f)]
        [SerializeField] private float slowMotionRate = 0.3f;

        private readonly ComboShowcaseSequence sequence = new ComboShowcaseSequence();
        private readonly CombatAnimatorBinding binding = new CombatAnimatorBinding();
        private readonly List<MeleeEvent> events = new List<MeleeEvent>(4);

        private CombatAnimationModel model;
        private MeleeComboProfile fallbackProfile;
        private Vector3 targetScale = Vector3.one;
        private float clock;
        private float rate = 1f;
        private float lastContact = float.NegativeInfinity;
        private int roundsSeen;
        private bool hasGrounded;

        public MagicDiscipline Discipline => discipline;
        public DisciplineDefinition Definition => definition;
        public CombatAnimationSet AnimationSet => animationSet;
        public Animator Figure => figure;
        public Transform Target => target;

        /// <summary>The rules' clock of this figure: game time, slowed during slow-motion rounds.</summary>
        public float Clock => clock;

        /// <summary>Connects only the references that are empty. Returns true if anything changed. Called by the setup tooling.</summary>
        public bool FillReferences(MagicDiscipline which, DisciplineDefinition asset, CombatAnimationSet set, Animator animator,
            Transform post, Renderer tint)
        {
            bool changed = false;
            if (definition == null && asset != null) { definition = asset; changed = true; }
            if (animationSet == null && set != null) { animationSet = set; changed = true; }
            if (figure == null && animator != null) { figure = animator; changed = true; }
            if (target == null && post != null) { target = post; changed = true; }
            if (marker == null && tint != null) { marker = tint; changed = true; }
            if (discipline != which && definition == null) { discipline = which; changed = true; }
            return changed;
        }

        private MeleeComboProfile Profile
        {
            get
            {
                if (definition != null && definition.Melee != null && definition.Melee.StepCount > 0)
                {
                    return definition.Melee;
                }

                return fallbackProfile ?? (fallbackProfile = DisciplineDefaults.Melee(discipline));
            }
        }

        private void OnEnable()
        {
            if (definition != null)
            {
                discipline = definition.Discipline;
            }

            model = animationSet != null ? new CombatAnimationModel(animationSet.Library) : null;
            model?.SetDiscipline(discipline);
            clock = 0f;
            rate = 1f;
            roundsSeen = 0;
            sequence.PauseSeconds = pauseSeconds;
            sequence.Restart(clock);

            if (target != null)
            {
                targetScale = target.localScale;
            }

            if (marker != null)
            {
                var block = new MaterialPropertyBlock();
                marker.GetPropertyBlock(block);
                Color color = definition != null ? definition.Color : DisciplineCatalog.Get(discipline).Color;
                block.SetColor(BaseColorId, color);
                marker.SetPropertyBlock(block);
            }

            if (figure != null && model != null && !binding.Bind(figure, animationSet.Library, out string problem))
            {
                Debug.LogWarning($"[Threefold] The {discipline} style figure cannot play: {problem}", this);
            }

            hasGrounded = false;
            if (figure != null)
            {
                foreach (AnimatorControllerParameter parameter in figure.parameters)
                {
                    hasGrounded |= parameter.nameHash == GroundedId && parameter.type == AnimatorControllerParameterType.Bool;
                }
            }
        }

        private void OnDisable()
        {
            binding.Release();
            if (figure != null)
            {
                figure.speed = 1f;
            }

            if (target != null)
            {
                target.localScale = targetScale;
            }
        }

        private void Update()
        {
            if (model == null || !binding.IsBound)
            {
                return;
            }

            clock += Time.deltaTime * rate;

            events.Clear();
            sequence.Tick(clock, Profile, events);
            for (int i = 0; i < events.Count; i++)
            {
                MeleeEvent melee = events[i];
                if (melee.Kind == MeleeEventKind.StepStarted && melee.Step != null)
                {
                    model.SwingStarted(discipline, melee.StepIndex, melee.Step.startupSeconds, melee.Step.recoverySeconds, clock);
                }
                else if (melee.Kind == MeleeEventKind.Hit)
                {
                    model.SwingLanded(clock);
                    lastContact = clock;
                }
            }

            model.Tick(clock, new CombatBodyState(true, 0f));
            model.Cues.Clear();

            // The figure stands on its plinth: the locomotion layer shows standing, never falling.
            if (hasGrounded)
            {
                figure.SetBool(GroundedId, true);
            }

            figure.speed = rate;
            binding.Apply(model);

            if (sequence.Round != roundsSeen)
            {
                roundsSeen = sequence.Round;
                rate = slowMotionEvery > 0 && (roundsSeen + 1) % slowMotionEvery == 0 ? slowMotionRate : 1f;
            }

            if (target != null)
            {
                // A short jolt at contact, in the rules' clock, so slow motion shows it slowly too.
                float since = clock - lastContact;
                float jolt = since >= 0f && since < 0.4f ? Mathf.Exp(-since * 14f) * 0.35f : 0f;
                target.localScale = new Vector3(targetScale.x * (1f + jolt), targetScale.y * (1f - jolt * 0.3f),
                    targetScale.z * (1f + jolt));
            }
        }
    }
}

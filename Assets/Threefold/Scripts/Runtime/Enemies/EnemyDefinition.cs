using UnityEngine;

namespace Threefold.Enemies
{
    /// <summary>
    /// One kind of enemy, as an asset: its name and tuning. Every enemy of that kind in every
    /// scene reads the same asset, so a value changed here changes them all.
    /// </summary>
    [CreateAssetMenu(menuName = "Threefold/Enemies/Enemy Definition", fileName = "NewEnemy")]
    public sealed class EnemyDefinition : ScriptableObject
    {
        [SerializeField] private string displayName = "Enemy";
        [SerializeField] private EnemyTuning tuning = new EnemyTuning();

        // Which version of the generated values this asset holds; see EnemyArchetypes.DataVersion.
        [SerializeField, HideInInspector] private int dataVersion;

        public string DisplayName => displayName;
        public int DataVersion => dataVersion;

        /// <summary>The tuning as authored. Enemies use a scaled copy; do not change it at runtime.</summary>
        public EnemyTuning Tuning => tuning;

        /// <summary>Sets the values. Called by the setup tooling.</summary>
        public void Configure(string enemyName, EnemyTuning enemyTuning)
        {
            displayName = enemyName;
            tuning = enemyTuning ?? new EnemyTuning();
            dataVersion = EnemyArchetypes.DataVersion;
        }

        /// <summary>
        /// Brings a definition generated by an earlier version up to date, once: it is given what that
        /// version did not have (stagger by force, armour, ward) from its archetype, unless any of those
        /// was already set by hand. Every other value is kept. Returns true if the asset was behind.
        /// </summary>
        public bool Upgrade(EnemyTuning archetype)
        {
            if (dataVersion >= EnemyArchetypes.DataVersion || archetype == null)
            {
                return false;
            }

            EnemyArchetypes.FillCombinations(tuning, archetype);
            dataVersion = EnemyArchetypes.DataVersion;
            return true;
        }
    }
}

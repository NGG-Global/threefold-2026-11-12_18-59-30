using UnityEngine;

namespace Threefold.WorldMagic
{
    /// <summary>
    /// How one kind of object responds to magic: which properties it has (thermal, structural,
    /// kinetic, arcane-reactive, stability) and their values. Put a <see cref="MagicalObject"/> on
    /// an object, give it one of these, and it responds; no script is written per object. Several
    /// objects can share a definition.
    /// </summary>
    [CreateAssetMenu(menuName = "Threefold/Magical Object Definition", fileName = "NewMagicalObject")]
    public sealed class MagicalObjectDefinition : ScriptableObject
    {
        [SerializeField] private string displayName = "Magical Object";

        [TextArea(2, 4)]
        [Tooltip("What the object is meant to do, for whoever tunes it.")]
        [SerializeField] private string notes = string.Empty;

        [SerializeField] private MagicalPropertySettings properties = new MagicalPropertySettings();

        // Which version of the generated values this asset holds; see WorldMagicDefaults.DataVersion.
        [SerializeField, HideInInspector] private int dataVersion;

        public int DataVersion => dataVersion;
        public string DisplayName => displayName;
        public string Notes => notes;
        public MagicalPropertySettings Properties => properties;

        /// <summary>Sets the values, as those of the current version. Called by the setup tooling and by tests.</summary>
        public void Configure(string objectName, string description, MagicalPropertySettings settings)
        {
            displayName = objectName;
            notes = description ?? string.Empty;
            properties = settings ?? new MagicalPropertySettings();
            dataVersion = WorldMagicDefaults.DataVersion;
        }

        /// <summary>
        /// Brings an example definition generated by an earlier version up to date, once: it is given
        /// what that version did not have yet (what is saved, what happens while switched off, its
        /// reactions) from the defaults of the same example, unless any of those was already set by
        /// hand. Every value that existed before is kept. Returns true if the asset was behind.
        /// </summary>
        public bool Upgrade(MagicalPropertySettings defaults)
        {
            if (dataVersion >= WorldMagicDefaults.DataVersion || defaults == null)
            {
                return false;
            }

            // Whether or not anything was filled in, the asset has now been looked at and is left alone.
            WorldMagicDefaults.FillWorldState(properties, defaults);
            dataVersion = WorldMagicDefaults.DataVersion;
            return true;
        }
    }
}

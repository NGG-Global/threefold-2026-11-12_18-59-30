using System.Collections.Generic;
using NUnit.Framework;
using Threefold.EditorTools;

namespace Threefold.Tests
{
    /// <summary>The naming rules that connect the exported character file to Unity.</summary>
    public sealed class CharacterSetupTests
    {
        [TestCase("Armature|Idle", "Idle")]
        [TestCase("Armature|Armature|SpellShoot", "SpellShoot")]
        [TestCase("Jog", "Jog")]
        [TestCase("", "")]
        public void ClipNamesDropTheBlenderPrefix(string take, string expected)
        {
            Assert.AreEqual(expected, CharacterModelPostprocessor.CleanClipName(take));
        }

        [TestCase("Idle", true)]
        [TestCase("Walk", true)]
        [TestCase("Jog", true)]
        [TestCase("Sprint", true)]
        [TestCase("JumpLoop", true)]
        [TestCase("JumpStart", false)]
        [TestCase("JumpLand", false)]
        [TestCase("SpellShoot", false)]
        [TestCase("Spell_Simple_Idle_Loop", true)]
        [TestCase("Idle_Shield_Loop", true)]
        [TestCase("Push_Loop", true)]
        [TestCase("Sword_Idle", true)]
        [TestCase("Punch_Jab", false)]
        [TestCase("Arcane_Stance_Loop", true)]
        [TestCase("Flame_Stance_Loop", true)]
        [TestCase("Aegis_Stance_Loop", true)]
        [TestCase("Arcane_RisingPalm", false)]
        [TestCase("Flame_Flare", false)]
        [TestCase("Aegis_Slam", false)]
        [TestCase("Sword_Attack", false)]
        [TestCase("Death01", false)]
        [TestCase("Loop", false)]
        [TestCase("", false)]
        public void OnlyContinuousMovementLoops(string clip, bool loops)
        {
            Assert.AreEqual(loops, CharacterModelPostprocessor.IsLooping(clip));
        }

        [TestCase("Assets/Threefold/Art/Characters/Mage/Mage.fbx", true)]
        [TestCase("Assets/Threefold/Art/Characters/Mage/Mage.FBX", true)]
        [TestCase("Assets/Threefold/Art/Props/Crate.fbx", false)]
        [TestCase("Assets/Threefold/Art/Characters/Mage/Notes.txt", false)]
        public void ImportRulesApplyOnlyToCharacterModels(string path, bool applies)
        {
            Assert.AreEqual(applies, CharacterModelPostprocessor.IsCharacterModel(path));
        }

        [TestCase("MAGE_Cloak", "Cloak")]
        [TestCase("MAGE_Crystal (Instance)", "Crystal")]
        [TestCase("Skin", "Skin")]
        public void ModelMaterialsMapToThePalette(string materialName, string key)
        {
            Assert.AreEqual(key, MageCharacterSetup.MaterialKey(materialName));
        }

        // ------------------------------------------------------------ the Mage's looks (Docs/Characters/Mage.md)

        [Test]
        public void TheWayfarerLookAndItsPaintingAreCharacterAssets()
        {
            Assert.IsTrue(CharacterModelPostprocessor.IsCharacterModel(CharacterModelPostprocessor.MageWayfarerModelPath));
            Assert.IsTrue(CharacterModelPostprocessor.IsCharacterTexture(CharacterModelPostprocessor.MagePaintTexturePath));
            Assert.IsFalse(CharacterModelPostprocessor.IsCharacterTexture(CharacterModelPostprocessor.MageModelPath));
            Assert.IsFalse(CharacterModelPostprocessor.IsCharacterTexture("Assets/Threefold/Generated/VisualStyle/Stone.png"));
            Assert.AreEqual("Paint", MageCharacterSetup.MaterialKey("MAGE_Paint"));
        }

        [Test]
        public void AFirstSetupUsesTheWayfarerLookOnlyWhenItIsUsable()
        {
            MageLookRules.Decision usable = MageLookRules.Decide(false, null, true);
            Assert.AreEqual(MageLook.Wayfarer, usable.Look);
            Assert.IsTrue(usable.Build);
            Assert.IsFalse(usable.ChosenByHand);

            MageLookRules.Decision unusable = MageLookRules.Decide(false, null, false);
            Assert.AreEqual(MageLook.Library, unusable.Look);
            Assert.IsTrue(unusable.Build);
        }

        [Test]
        public void APrefabMadeBeforeLooksExistedIsUpgradedOnce()
        {
            // No stamp: generated by an earlier version, so it holds the library look.
            MageLookRules.Decision first = MageLookRules.Decide(true, string.Empty, true);
            Assert.AreEqual(MageLook.Wayfarer, first.Look);
            Assert.IsTrue(first.Build);

            MageLookRules.Decision second = MageLookRules.Decide(true, MageLookRules.Stamp(first.Look, first.ChosenByHand), true);
            Assert.AreEqual(MageLook.Wayfarer, second.Look);
            Assert.IsFalse(second.Build, "Running the setup again must change nothing.");
        }

        [Test]
        public void AnOlderPrefabIsKeptWhileTheWayfarerModelIsUnusable()
        {
            MageLookRules.Decision decision = MageLookRules.Decide(true, null, false);
            Assert.AreEqual(MageLook.Library, decision.Look);
            Assert.IsFalse(decision.Build);
        }

        [Test]
        public void AWayfarerModelThatStopsBeingUsableGivesWayToTheLibraryLook()
        {
            foreach (bool byHand in new[] { false, true })
            {
                MageLookRules.Decision decision = MageLookRules.Decide(true, MageLookRules.Stamp(MageLook.Wayfarer, byHand), false);
                Assert.AreEqual(MageLook.Library, decision.Look);
                Assert.IsTrue(decision.Build);
                Assert.IsFalse(decision.ChosenByHand);
            }
        }

        [Test]
        public void ALookChosenByHandIsKeptBySetupRuns()
        {
            MageLookRules.Decision library = MageLookRules.Decide(true, MageLookRules.Stamp(MageLook.Library, true), true);
            Assert.AreEqual(MageLook.Library, library.Look);
            Assert.IsFalse(library.Build);
            Assert.IsTrue(library.ChosenByHand);

            MageLookRules.Decision wayfarer = MageLookRules.Decide(true, MageLookRules.Stamp(MageLook.Wayfarer, true), true);
            Assert.AreEqual(MageLook.Wayfarer, wayfarer.Look);
            Assert.IsFalse(wayfarer.Build);
        }

        [TestCase(false, false)]
        [TestCase(false, true)]
        [TestCase(true, false)]
        [TestCase(true, true)]
        public void StampsReadBackAsWritten(bool wayfarer, bool byHand)
        {
            MageLook look = wayfarer ? MageLook.Wayfarer : MageLook.Library;
            MageLookRules.ReadStamp(MageLookRules.Stamp(look, byHand), out MageLook readLook, out bool readByHand);
            Assert.AreEqual(look, readLook);
            Assert.AreEqual(byHand, readByHand);
        }

        [TestCase(null)]
        [TestCase("")]
        [TestCase("threefold-mage-controller-5")]
        [TestCase("threefold-mage-visual-1|Wayfarer|chosen")]
        [TestCase("threefold-mage-visual-2|Nonsense|auto")]
        public void AnUnknownStampMeansTheLibraryLookChosenByNobody(string stamp)
        {
            MageLookRules.ReadStamp(stamp, out MageLook look, out bool byHand);
            Assert.AreEqual(MageLook.Library, look);
            Assert.IsFalse(byHand);
        }

        private static List<KeyValuePair<string, string>> Mapping(params string[] pairs)
        {
            var list = new List<KeyValuePair<string, string>>();
            for (int i = 0; i + 1 < pairs.Length; i += 2)
            {
                list.Add(new KeyValuePair<string, string>(pairs[i], pairs[i + 1]));
            }

            return list;
        }

        [Test]
        public void TheSameHumanoidMappingIsAccepted()
        {
            List<KeyValuePair<string, string>> library = Mapping("Hips", "pelvis", "Spine", "spine_01", "Head", "Head");
            List<KeyValuePair<string, string>> reordered = Mapping("Head", "Head", "Hips", "pelvis", "Spine", "spine_01");
            Assert.IsNull(MageLookRules.CompareHumanMappings(library, reordered));
        }

        [Test]
        public void AHumanBoneMappedToAnExtraBoneIsRejected()
        {
            List<KeyValuePair<string, string>> library = Mapping("Hips", "pelvis", "Chest", "spine_02", "Head", "Head");
            List<KeyValuePair<string, string>> wrong = Mapping("Hips", "pelvis", "Chest", "sec_cloak_l_01", "Head", "Head");
            StringAssert.Contains("sec_cloak_l_01", MageLookRules.CompareHumanMappings(library, wrong));
        }

        [Test]
        public void AMissingOrAdditionalHumanBoneIsRejected()
        {
            List<KeyValuePair<string, string>> library = Mapping("Hips", "pelvis", "Head", "Head");
            StringAssert.Contains("Head", MageLookRules.CompareHumanMappings(library, Mapping("Hips", "pelvis")));
            StringAssert.Contains("Jaw", MageLookRules.CompareHumanMappings(library,
                Mapping("Hips", "pelvis", "Head", "Head", "Jaw", "face_brows")));
            Assert.IsNotNull(MageLookRules.CompareHumanMappings(library, Mapping()));
            Assert.IsNotNull(MageLookRules.CompareHumanMappings(Mapping(), library));
        }
    }
}
